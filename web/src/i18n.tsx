const dictionaries: Record<Language, Dictionary> = { ar, en };

const STORAGE_KEY = "engines.language";

function storedLanguage(): Language {
  try {
    return localStorage.getItem(STORAGE_KEY) === "en" ? "en" : "ar";
  } catch {
    return "ar";
  }
}

/** A message with `{name}` slots filled in. */
export function fill(
  message: string,
  values: Record<string, string | number>,
): string {
  return message.replace(/\{(\w+)\}/g, (_, name: string) =>
    String(values[name] ?? ""),
  );
}

/** A document status in words; one the page doesn't know yet shows as it is. */
export function statusLabel(t: Dictionary, status: string): string {
  const labels: Record<string, string | undefined> = t.statuses;
  return labels[status] ?? status;
}

interface I18n {
  t: Dictionary;
  language: Language;
  toggle: () => void;
  /** Numbers and dates written the way the language writes them. */
  number: (n: number) => string;
  date: (iso: string) => string;
}

const Context = createContext<I18n | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(storedLanguage);
  useEffect(() => {
    document.documentElement.lang = language;
    document.documentElement.dir = language === "ar" ? "rtl" : "ltr";
    try {
      localStorage.setItem(STORAGE_KEY, language);
    } catch {
      // Private windows: the choice lasts until the page closes.
    }
  }, [language]);
  const locale = language === "ar" ? "ar" : "en";
  const value: I18n = {
    t: dictionaries[language],
    language,
    toggle: () => {
      setLanguage((l) => (l === "ar" ? "en" : "ar"));
    },
    number: (n) => new Intl.NumberFormat(locale).format(n),
    date: (iso) =>
      new Intl.DateTimeFormat(locale, { dateStyle: "medium" }).format(
        new Date(iso),
      ),
  };
  return <Context value={value}>{children}</Context>;
}

export function useI18n(): I18n {
  const value = useContext(Context);
  if (!value) throw new Error("useI18n outside I18nProvider");
  return value;
}
